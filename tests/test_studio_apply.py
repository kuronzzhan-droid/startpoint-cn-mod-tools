@pytest.mark.parametrize("action", ["apply", "unapply", "overlay"])
@pytest.mark.parametrize("body", [b'{"root":"untrusted"}', b'[]', b'"dryRun"', b'null', b'false', b'1'])
def test_actions_pass_through_write_guard_without_network(enabled, tmp_path, action, body):
    import io as streams
    from types import SimpleNamespace
    from test_studio_deliver_routes import _FakeSource
    from wf.studio.deliver_routes import DeliverRoutes
    from wf.studio.drafts import DraftStore
    from wf.studio.guard import WriteGuard
    from wf.studio.server import StudioApp, make_handler
    root, folder, _ = enabled
    name = "199000-1.4.9-to-1.4.10-20261101-120000"
    renamed = folder.parent.with_name(name)
    folder.parent.rename(renamed)
    app = StudioApp(_FakeSource(), drafts=DraftStore(tmp_path / "drafts"))
    app.routes = DeliverRoutes(app, root=renamed.parent).routes()
    guard = WriteGuard(8790)
    handler = make_handler(app, tmp_path, guard)
    class Request:
        def __init__(self, raw):
            self.input = streams.BytesIO(raw)
            self.output = bytearray()
        def makefile(self, *args):
            return self.input
        def sendall(self, data):
            self.output.extend(data)
        def gettimeout(self):
            return None
        def settimeout(self, value):
            pass
    before = snapshot(root)
    for headers, expected in [("", 403), (f"X-WF-Studio-Token: {guard.token}\r\nOrigin: https://invalid.example\r\n", 403),
                              (f"X-WF-Studio-Token: {guard.token}\r\n", 400)]:
        # A valid token must reach field validation and reject arbitrary paths.
        raw = (f"POST /api/deliveries/{name}/{action} HTTP/1.1\r\nHost: 127.0.0.1:8790\r\n"
               f"Connection: close\r\nContent-Type: application/json\r\nContent-Length: {len(body)}\r\n"
               + headers + "\r\n").encode() + body
        request = Request(raw)
        handler(request, ("127.0.0.1", 12345), SimpleNamespace())
        assert int(request.output.split(b" ")[1]) == expected
    assert snapshot(root) == before
