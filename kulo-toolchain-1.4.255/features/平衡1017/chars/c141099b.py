# -*- coding: utf-8 -*-
"""护花使龙 休尔特 141099（wind_dragon_wt22）—— 平衡表（水鱼）「加强只针对超限后」：只改觉醒(超限)替换行（c3=1 且 c4=1）。
新增行 = 复制同键觉醒行改 kind/数值，紧跟其后。低级数值按觉醒行原来的低/满比例（能力 1/2，队长 3/4）。
主位 = precondition kind 202（照 119991#1）；独立乘区强化弹射 = 696（照 1199926 米娅）；强化弹射伤害 = 55。"""
import copy
from common import *

def awake(r):
    return r[3] == "1" and r[4] == "1"

def clone(r, kind, s1, s2):
    n = copy.deepcopy(r); n[AB_IC_KIND] = kind; n[AB_IC_S1] = str(s1); n[AB_IC_S2] = str(s2); return n

def apply(F):
    # 队长 L3 攻击力 18%(限10) → 40%(限5)；删 L5 技能伤害 10%
    le = F.le("141099")
    r = le[3]
    assert r[1] == "1" and r[45] == "32" and r[32] == "10"
    setv(r, [49], 13500, 30000); setv(r, [50], 18000, 40000); setv(r, [32], 10, 5)
    assert le[5][1] == "1" and le[5][45] == "34" and le[5][50] == "10000"
    del le[5]
    F.log("休尔特（超限后）队长技：每2次强化弹射 风属性角色攻击力 +18%（最大+180%）→ +40%（最大+200%）；"
          "删去「技能伤害+10%（最大+100%）」；强化弹射伤害 +15%（最大+150%）不变")
    # 能力1：主位 + 风共鸣；新增 独立乘区强化弹射 25%
    ab = F.ab("1410991"); r = ab[1]
    assert awake(r) and r[27] == "58" and r[47] == "32" and r[52] == "100000" and all(x in EMPTY for x in r[6:20])
    r[AB_P1] = "202"
    gate(r, AB_P2, "Green")
    ab.insert(2, clone(r, "696", 12500, 25000))
    F.log("休尔特（超限后）能力1：自身攻击力+100% 改为「作为主要角色编成、风属性共鸣时」生效，并新增对敌人强化弹射伤害+25%（独立乘区）")
    # 能力2：去 风·MySelf 改主位；攻击 15%(限10) → 30%(限5)；新增 强化弹射伤害 30%(限5)
    ab = F.ab("1410992"); r = ab[1]
    assert awake(r) and (r[6], r[11], r[34], r[47]) == ("3", "Green", "10", "32")
    r[6:13] = ["202", "", "", "", "", "", ""]
    setv(r, [AB_IC_S1], 7500, 15000); setv(r, [AB_IC_S2], 15000, 30000); setv(r, [AB_TRIG_LIMIT], 10, 5)
    ab.insert(2, clone(r, "55", 15000, 30000))
    F.log("休尔特（超限后）能力2：改为「作为主要角色编成」，每2次强化弹射 自身攻击力 +15%（最大+150%）→ +30%（最大+150%），"
          "新增强化弹射伤害 +30%（最大+150%）")
    # 能力3：攻击 22.5%(限10) → 45%(限5)；新增 强化弹射伤害 45%(限5)
    ab = F.ab("1410993"); r = ab[3]
    assert awake(r) and (r[34], r[47]) == ("10", "32")
    setv(r, [AB_IC_S1], 11250, 22500); setv(r, [AB_IC_S2], 22500, 45000); setv(r, [AB_TRIG_LIMIT], 10, 5)
    ab.insert(4, clone(r, "55", 22500, 45000))
    F.log("休尔特（超限后）能力3（主位）：每2次强化弹射 自身攻击力 +22.5%（最大+225%）→ +45%（最大+225%），新增强化弹射伤害 +45%（最大+225%）")
    # 能力4：技能槽 62.5% → 75%；新增 强化弹射伤害 150%
    ab = F.ab("1410994"); r = ab[1]
    assert awake(r) and r[47] == "211"
    setv(r, [AB_IC_S1], 31250, 37500); setv(r, [AB_IC_S2], 62500, 75000)
    ab.insert(2, clone(r, "55", 75000, 150000))
    F.log("休尔特（超限后）能力4：战斗开始时自身技能槽 +62.5%→+75%，新增强化弹射伤害 +150%")
    # 能力5/6：攻击 5.6%(限10) → 12%(限5)；新增 强化弹射伤害 12%(限5)
    for k in ("1410995", "1410996"):
        ab = F.ab(k); r = ab[1]
        assert awake(r) and (r[6], r[34], r[47]) == ("3", "10", "32")
        setv(r, [AB_IC_S1], 2800, 6000); setv(r, [AB_IC_S2], 5600, 12000); setv(r, [AB_TRIG_LIMIT], 10, 5)
        ab.insert(2, clone(r, "55", 6000, 12000))
    F.log("休尔特（超限后）能力5、能力6：自身是风属性时每2次强化弹射 自身攻击力 +5.6%（最大+56%）→ +12%（最大+60%），新增强化弹射伤害 +12%（最大+60%）")
