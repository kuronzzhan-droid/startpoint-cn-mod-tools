# -*- coding: utf-8 -*-
"""破契的黑鸦 基诺维 169999 —— 平衡表（Shazixnar 10-18 00:59）。
技能（两档）：全体敌人全属性抗性降低 10%→5%，命中敌人暗属性抗性降低 15%→5%。
队长：每保持贯穿1.5秒 暗属性角色攻击/技能/能力伤害 +25%（3次）→ +10%（40次）；死印每层全伤害 +1% → +0.5%（乘区2，10层），加暗属性共鸣。"""
from dsltools import commands
from common import *

def apply(F):
    for lv in ("1", "2"):
        t = F.dsl(f"battle/action/skill/action/rare5/ginovi$ginovi_{lv}")
        n = {254: 0, 6: 0}
        for pp, c in commands(t, "CreateCondition"):
            k = c[2][0]
            if k[0] == "ACToleranceOfElement":
                if k[2] == 254:
                    assert k[3] == [{"min": -0.1, "max": -0.1}]; k[3] = [{"min": -0.05, "max": -0.05}]
                else:
                    assert k[2] == 6 and k[3] == [{"min": -0.15, "max": -0.15}]; k[3] = [{"min": -0.05, "max": -0.05}]
                n[k[2]] += 1
        assert n == {254: 2, 6: 1}, (lv, n)
    F.log("基诺维 技能『掠影协奏』：全体敌人全属性抗性降低 10%→5%，命中敌人暗属性抗性降低 15%→5%")
    le = F.le("169999")
    for i, k in ((6, "32"), (7, "34"), (8, "388")):
        r = le[i]
        assert r[25] == "235" and r[45] == k and r[32] == "3"
        setv(r, [49, 50], 25000, 10000); setv(r, [32], 3, 40)
    r = le[10]
    assert (r[95], r[102], r[107]) == ("171", "1699901", "158") and r[4] in EMPTY
    setv(r, [111, 112], 1000, 500)
    gate(r, LE_P1, "Black")
    F.log("基诺维 队长技：暗属性共鸣时每保持贯穿1.5秒，暗属性角色攻击力、技能伤害、能力伤害各 +25%（最多3次）→ +10%（最多40次）；"
          "敌人「死印」每1层队伍全体伤害 +1% → +0.5%（独立伤害乘区2，最多10层），并改为需暗属性共鸣")
    F.cas_replace("desc_override_ginovi", [
        ("暗属性角色攻击力+25%、技能伤害+25%、能力伤害+25%（最多3次）", "暗属性角色攻击力+10%、技能伤害+10%、能力伤害+10%（最多40次）"),
        ("敌人持有的「死印」每1层，队伍全体对该敌人造成的伤害+1%（独立伤害乘区2）（最多10层）",
         "暗属性共鸣时，敌人持有的「死印」每1层，队伍全体对该敌人造成的伤害+0.5%（独立伤害乘区2）（最多10层）")])
