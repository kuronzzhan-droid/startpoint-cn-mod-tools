def klaus(F):
    F.owner = "r11_129997"
    t = F.table(ST)
    v = F.string(ST, "129997")
    d = dict(v) if isinstance(v, dict) else None
    assert d is not None and d["100"].split(",")[1] == "525", d
    # 表上「攻击白值 648→800」= 满级面板，含进化/觉醒等固定加值 123；只抬基础曲线：Lv100 525→677，各级同比例
    k = 677 / 525
    nd = {}
    for lv, s in d.items():
        hp, atk = s.split(",")
        nd[lv] = f"{hp},{int(round(int(atk) * k))}"
    assert nd["100"].split(",")[1] == "677"
    F.set_string(ST, "129997", nd)
    F.log("克劳斯 基础：攻击白值 648→800（满级基础攻击 525→677，各等级按同比例抬高）")


