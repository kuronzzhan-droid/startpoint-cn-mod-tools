def apply(F):
    le = F.le("119990")
    k = [r[45] if r[3] != "1" else "d" + r[107] for r in le]
    assert k[1] == "34" and k[2] == "32" and k[4] == "461" and k[9] == "34" and k[10] == "d2" and k[11] == "d0" and k[12] == "d411", k
    setv(le[1], [49, 50], 100000, 40000); setv(le[1], [32], 3, 15)
    setv(le[2], [49, 50], 50000, 20000); setv(le[2], [32], 3, 15)
    setv(le[4], [49, 50], 400000, 700000)
    setv(le[11], [111, 112], 45000, 15000); setv(le[11], [100], 3, 30)
    setv(le[12], [111, 112], 3500, 500); setv(le[12], [100], 3, 30)
    assert le[9][32] == "3" and le[10][100] == "3"
    del le[10]; del le[9]
    F.log("玛格诺斯 队长技：火属性共鸣时每3次强化弹射 火属性角色技能伤害 +100%→+40%、攻击力 +50%→+20%（最多 3→15 次），"
          "技能槽+5% 不变，引擎点火 +4→+7 层，删去自身技能伤害+25%；引擎点火每层 删去自身技能伤害+45%，自身攻击力 +45%→+15%，"
          "火属性角色技能伤害 +3.5%→+0.5%（独立伤害乘区7），最多 3→30 层")
    F.cas_replace("desc_override_lion_swordman_moon", [
        ("火属性角色技能伤害+100%、攻击力+50%（最多3次）", "火属性角色技能伤害+40%、攻击力+20%（最多15次）"),
        ("火属性共鸣时，每发动3次强化弹射，自身技能伤害+25%（最多3次）\n", ""),
        ("自身获得4层「引擎点火」", "自身获得7层「引擎点火」"),
        ("「引擎点火」每1层，自身技能伤害+45%、攻击力+45%（最多3层）", "「引擎点火」每1层，自身攻击力+15%（最多30层）"),
        ("火属性角色技能伤害+3.5%（独立伤害乘区7）（最多3层）", "火属性角色技能伤害+0.5%（独立伤害乘区7）（最多30层）")])
