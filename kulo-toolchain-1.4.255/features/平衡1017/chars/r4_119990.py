    F.log("玛格诺斯 能力1：火属性共鸣时每3次强化弹射 自身技能伤害 +25%（最多4次）→ +20%（最多30次）")
    F.cas_replace("desc_override_lion_swordman_moon_1", [("自身技能伤害+25%（最多4次）", "自身技能伤害+20%（最多30次）")])
    r = F.ab("1199903")[5]
    assert (r[27], r[47], r[68]) == ("2", "461", "11999001")
