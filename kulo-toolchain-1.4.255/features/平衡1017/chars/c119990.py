# -*- coding: utf-8 -*-
"""月下归途的机车骑士 玛格诺斯 119990 —— 平衡表 1017（PPPP 10-17 4:27）：放慢引擎点火暖机。
引擎点火 = unique 11999001（上限 99 层）。461 赋予固有：strength 100000 = 1 层，initial_multiply 为倍数。"""
from common import *

def apply(F):
    le = F.le("119990")
    r = le[4]
    assert (r[25], r[28], r[45], r[66], r[72]) == ("2", "300000", "461", "11999001", "1")
    setv(r, [49, 50], 700000, 400000)
    r = le[12]
    assert (r[107], r[100], r[102]) == ("411", "3", "11999001")
    setv(r, [111, 112], 5000, 3500)
    F.log("玛格诺斯 队长技：火属性共鸣时每发动3次强化弹射 引擎点火 +7层→+4层；引擎点火每层火属性角色技能伤害额外乘区 +5%→+3.5%（最多计3层）")
    F.cas_replace("desc_override_lion_swordman_moon", [
        ("引擎点火＋7层", "引擎点火＋4层"),
        ("火属性角色技能伤害额外乘区＋5%（最多计3层）", "火属性角色技能伤害额外乘区＋3.5%（最多计3层）")])
    ab3 = F.ab("1199903")
    r = ab3[0]
    assert (r[27], r[47], r[68]) == ("23", "461", "11999001") and r[35] in EMPTY
    r[35] = "240"
    r = ab3[2]
    assert (r[47], r[68]) == ("525", "11999001")
    setv(r, [AB_IC_S1, AB_IC_S2], 100000, 200000)
    r = ab3[3]
    assert (r[97], r[104], r[109]) == ("134", "11999001", "411")
    setv(r, [AB_DT_TH1, AB_DT_TH2], 500000, 600000)
    setv(r, [AB_DC_S1, AB_DC_S2], 10000, 5000)
    r = ab3[4]
    assert (r[97], r[104], r[109]) == ("134", "11999001", "411")
    setv(r, [AB_DT_LIMIT], 10, 15)
    setv(r, [AB_DC_S1, AB_DC_S2], 500, 330)
    r = ab3[5]
    assert (r[27], r[47], r[68]) == ("2", "461", "11999001")
    setv(r, [AB_TRIG_TH1, AB_TRIG_TH2], 300000, 400000)
    setv(r, [74], 3, 1)
    F.log("玛格诺斯 能力3：发动技能时引擎点火+1层 加 CT 4秒；技能命中时消耗引擎点火 1层→2层；"
          "引擎点火 5层以上 技能伤害额外乘区 +10% → 6层以上 +5%；每层火属性角色技能伤害额外乘区 +0.5%（最多10层）→ +0.33%（最多15层）；"
          "每发动3次强化弹射引擎点火+3层 → 每发动4次强化弹射+1层")
    F.cas_replace("desc_override_lion_swordman_moon_3", [
        ("火属性角色发动技能时，自身引擎点火＋1层", "火属性角色发动技能时，自身引擎点火＋1层（CT：4秒）"),
        ("消耗1层「引擎点火」", "消耗2层「引擎点火」"),
        ("自身引擎点火在5层以上时：自身技能伤害额外乘区＋10%", "自身引擎点火在6层以上时：自身技能伤害额外乘区＋5%"),
        ("火属性角色技能伤害额外乘区＋0.5%（最多10层）", "火属性角色技能伤害额外乘区＋0.33%（最多15层）"),
        ("每发动3次强化弹射，自身引擎点火＋3层", "每发动4次强化弹射，自身引擎点火＋1层")])
    ab5 = F.ab("1199905")
    r = ab5[0]
    assert r[47] == "694" and all(x in EMPTY for x in r[6:27])
    gate(r, AB_P1, "Red")
    setv(r, [AB_IC_S1, AB_IC_S2], 15000, 10000)
    r = ab5[1]
    assert (r[27], r[47]) == ("2", "211")
    setv(r, [AB_TRIG_TH1, AB_TRIG_TH2], 300000, 400000)
    setv(r, [AB_TRIG_CT], 300, 360)
    setv(r, [AB_IC_S1, AB_IC_S2], 5000, 4000)
    F.log("玛格诺斯 能力5：独立乘区技能伤害 +15%→+10% 并改为需火属性共鸣；每发动3次强化弹射技能槽+5%（CT 5秒）→ 每4次 +4%（CT 6秒）")
    F.cas_replace("desc_override_lion_swordman_moon_5", [
        ("自身独立乘区技能伤害＋15%", "火属性共鸣时，自身独立乘区技能伤害＋10%"),
        ("每发动3次强化弹射，自身技能槽＋5%（冷却时间：5秒）", "每发动4次强化弹射，自身技能槽＋4%（冷却时间：6秒）")])
