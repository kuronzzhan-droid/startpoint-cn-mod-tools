"""月相夜课的导师 妮可拉 119991 —— 平衡表 1017（PPPP 10-17 3:51）：能力2、能力3 数值下调。"""
from .common import *

def apply(F):
    r = F.ab("1199912")[0]
    assert r[47] == "34" and r[34] == "5"
    setv(r, [AB_IC_S1], 25000, 10000); setv(r, [AB_IC_S2], 50000, 20000)
    F.log("妮可拉 能力2：火属性共鸣时，自身发动技能时火属性角色技能伤害 +50%（最多5次，最大+250%）→ +20%（最大+100%）")
    ab3 = F.ab("1199913")
    r = ab3[2]
    assert r[47] == "32" and r[34] == "3"
    setv(r, [AB_IC_S1, AB_IC_S2], 65000, 20000)
    for i, k in ((6, "503"), (7, "550")):
        assert ab3[i][47] == k
        setv(ab3[i], [AB_IC_S1, AB_IC_S2], 300000, 100000)
    assert ab3[8][47] == "694"
    setv(ab3[8], [AB_IC_S1, AB_IC_S2], 15000, 2000)
    F.log("妮可拉 能力3：消耗「月讲」时该角色攻击力 +65%→+20%；火属性共鸣时对抗性降低中的敌人 攻击力 +300%→+100%、"
          "技能伤害 +300%→+100%，技能伤害额外乘区 +15%→+2%")
    F.cas_replace("desc_override_sorceress_teacher_moon_3", [
        ("攻击力＋65%", "攻击力＋20%"),
        ("攻击力＋300%、技能伤害＋300%，对敌人的技能额外伤害乘区＋15%", "攻击力＋100%、技能伤害＋100%，对敌人的技能额外伤害乘区＋2%")])
