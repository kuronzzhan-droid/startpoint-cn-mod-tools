from .common import *

def to_party_ability(r, kc, tc, gc):
    assert r[kc] == "28" and r[tc] in EMPTY and r[gc] in EMPTY, r[kc:gc + 1]
    r[kc] = "486"; r[tc] = "5"; r[gc] = "(None)"

def apply(F):
    le = F.le("169980")
    r = le[6]
    assert (r[95], r[100], r[102], r[107]) == ("134", "4", "180001", "421")
    setv(r, [111, 112], 25000, 10000)
    r = le[11]
    assert (r[4], r[7], r[25]) == ("188", "300000", "65")
    to_party_ability(r, 45, 46, 47)
    F.log("深渊之兽 队长技：深渊相位每升1级 暗属性角色伤害（独立乘区）+25%（最大+100%）→ +10%（最大+40%）；"
          "相位3个以上发动强化弹射Lv3时 赋予5秒「自身强化弹射伤害+50%」→「全队能力伤害+50%」")
    ab2 = F.ab("1699802")
    for i, tgt, k, o, n in ((0, "0", "0", 60000, 25000), (1, "0", "154", 120000, 25000),
                            (2, "5", "0", 25000, 30000), (3, "5", "154", 25000, 60000)):
        r = ab2[i]
        assert r[110] == tgt and r[109] == k and r[104] == "180001", (i, r[97:115])
        setv(r, [AB_DC_S1, AB_DC_S2], o, n)
    r = ab2[4]
    assert r[109] == "421" and r[110] in EMPTY and r[111] in EMPTY, r[109:112]
    r[110] = "5"; r[111] = "Black"
