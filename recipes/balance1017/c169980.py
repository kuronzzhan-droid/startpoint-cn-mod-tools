    F.log("深渊之兽 能力2：深渊相位每升1级（最多4级）—— 自身攻击力 +60%→+25%、自身能力伤害 +120%→+25%、"
          "暗属性角色攻击力 +25%→+30%、暗属性角色能力伤害 +25%→+60%；伤害（独立乘区）自身 +20% → 暗属性角色 +5%")
