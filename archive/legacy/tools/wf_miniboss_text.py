def ability_panel_text(cid, slot):
    """第 slot 个能力的面板文字；多行面板按行分开，主位槽（3）每一行都以主位图标开头。"""
    prefix = MAIN if slot == 3 else ""
    return "\n".join(prefix + line for line in TEXTS[str(cid)][slot - 1].split("\n"))


